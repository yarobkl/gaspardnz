-- Storage minimal, pour que le harness teste aussi le bucket site-media.
create schema if not exists storage;
grant usage on schema storage to anon, authenticated, service_role;
create table storage.objects (
  id uuid primary key default gen_random_uuid(),
  bucket_id text not null,
  name text not null
);

-- RLS activé comme en production.
do $$
declare t text;
begin
  foreach t in array array[
    'activity_log','admin_access','analytics_events','audit_log','bookings',
    'content_albums','crm_notes','customers','email_events','email_messages',
    'external_metric_snapshots','integration_credentials','integration_settings',
    'leads','media_assets','news_posts','oauth_states','packages','partner_contacts',
    'partners','promotions','public_rate_limits','sessions','site_content',
    'site_settings','style_month','vip_clients','visitors','wedding_inspirations'
  ] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;
alter table storage.objects enable row level security;

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant select, insert, update, delete on storage.objects to authenticated;
grant select on storage.objects to anon;

grant select on public.site_settings, public.site_content, public.content_albums,
  public.media_assets, public.news_posts, public.packages, public.partners,
  public.promotions, public.style_month, public.vip_clients,
  public.wedding_inspirations to anon;
