-- Contrat de schéma utilisé par le harness RLS.
--
-- Cette version est alignée sur les types/colonnes réellement constatés sur le
-- projet Supabase GaspardNZ (PostgreSQL 17) au 2026-09-10. Elle reste minimale
-- (toutes les colonnes métier non nécessaires aux tests ne sont pas recopiées),
-- mais les TYPES et RELATIONS touchés par les migrations sont fidèles.

create type public.admin_role as enum ('owner','admin','editor','viewer');
create type public.lead_status as enum ('new','contacted','qualified','appointment','client','lost','archived');
create type public.booking_status as enum ('requested','confirmed','completed','cancelled','no_show');
create type public.email_status as enum ('queued','sent','delivered','opened','clicked','failed','bounced');
create type public.promotion_status as enum ('draft','scheduled','active','expired','archived');

create table public.admin_access (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  role public.admin_role not null default 'viewer',
  display_name text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.visitors (
  id uuid primary key default gen_random_uuid(),
  last_seen_at timestamptz not null default now()
);
create table public.sessions (
  id uuid primary key default gen_random_uuid(),
  visitor_id uuid references public.visitors(id),
  started_at timestamptz not null default now()
);
create table public.analytics_events (
  id bigint generated by default as identity primary key,
  session_id uuid references public.sessions(id),
  visitor_id uuid references public.visitors(id),
  event_name text not null,
  created_at timestamptz not null default now()
);

create table public.leads (
  id uuid primary key default gen_random_uuid(),
  email text,
  full_name text,
  phone text,
  request_type text,
  message text,
  source text,
  status public.lead_status not null default 'new',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.customers (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid references public.leads(id),
  email text,
  full_name text not null,
  phone text,
  source text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid references public.leads(id),
  customer_id uuid references public.customers(id),
  provider text not null default 'calendly',
  status public.booking_status not null default 'requested',
  starts_at timestamptz,
  ends_at timestamptz,
  title text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.crm_notes (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid references public.leads(id),
  customer_id uuid references public.customers(id),
  body text not null,
  created_by text,
  created_at timestamptz not null default now()
);
create table public.email_messages (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid references public.leads(id),
  booking_id uuid references public.bookings(id),
  recipient text not null,
  subject text not null,
  status public.email_status not null default 'queued',
  queued_at timestamptz not null default now(),
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.email_events (
  id bigint generated by default as identity primary key,
  email_message_id uuid references public.email_messages(id),
  event_type text not null,
  created_at timestamptz not null default now()
);

create table public.site_settings (
